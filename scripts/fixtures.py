"""Generate MoonBit fixture tests and the usage guide from tests/cases.json.

    python -B scripts/fixtures.py          # rewrite fixtures_wbtest.mbt and docs/usage.md
    python -B scripts/fixtures.py --check  # fail when either file is out of date
"""
import json
import subprocess
import sys
from pathlib import Path

root = Path(__file__).resolve().parents[1]
cases = json.loads((root / 'tests/cases.json').read_text(encoding='utf-8'))

USAGE_HEADER = """# Request and result guide

Every example below is an executable fixture from `tests/cases.json`. The same cases run as MoonBit white-box tests on every backend (`fixtures_wbtest.mbt`) and through the Node CLI (`scripts/check.mjs`). Assertions cover the listed result fields; additional output fields are documented by the API and other fixtures. Error cases intentionally reject the request. This file is generated by `scripts/fixtures.py`.
"""

USAGE_FOOTER = """## Host adapter

```sh
node scripts/execute.mjs WORKFLOW.json WORKSPACE_DIR
```

The executor hashes declared files with SHA-256, asks the planner for the next ready wave, runs those commands as child processes (argv arrays, `shell=false`) with timeouts and retries, and repeats until the plan is terminal. It writes `.taskforge-cache.json` and `.taskforge-journal.json` into the workspace. Read the current boundaries before using this adapter.
"""


def mbt_string(text):
    return '"' + text.replace('\\', '\\\\').replace('"', '\\"') + '"'


def path_parts(key):
    if key.startswith('origins/'):
        return ['origins', key[len('origins/'):]]
    return key.split('/')


def render_tests():
    out = ['// Generated from tests/cases.json by scripts/fixtures.py; do not edit.', '']
    out += ['///|', 'fn test_at(value : Value, parts : Array[String]) -> Value raise {',
            '  let mut current = value', '  for part in parts {', '    current = match current {',
            '      Object(fields) =>', '        match fields.get(part) {', '          Some(v) => v',
            '          None => raise InputError("test key missing: " + part)', '        }',
            '      Array(items) => items[num(parse(part)).to_int()]',
            '      _ => raise InputError("invalid test traversal")', '    }', '  }', '  current', '}', '']
    out += ['///|', 'fn fails(request : String) -> Bool {',
            '  try {', '    ignore(run(parse(request)))', '    false',
            '  } catch {', '    _ => true', '  }', '}', '']
    for case in cases:
        request = mbt_string(json.dumps(case['request'], separators=(',', ':'), ensure_ascii=False))
        out += ['///|', f'test {mbt_string(case["name"])} {{']
        if case.get('error'):
            out.append(f'  assert_true(fails({request}))')
        else:
            out.append(f'  let result = run(parse({request}))')
            for key, expected in case['expected'].items():
                parts = ', '.join(mbt_string(p) for p in path_parts(key))
                value = mbt_string(json.dumps(expected, separators=(',', ':'), ensure_ascii=False))
                out.append(f'  assert_eq(test_at(result, [{parts}]), parse({value}))')
        out += ['}', '']
    return '\n'.join(out)


def render_usage():
    out = [USAGE_HEADER]
    for case in cases:
        out.append(f'## {case["name"]}\n')
        if case.get('note'):
            out.append(case['note'] + '\n')
        out.append('```json\n' + json.dumps(case['request'], indent=2, ensure_ascii=False) + '\n```\n')
        if case.get('error'):
            out.append('Expected: nonzero exit with an input error.\n')
        else:
            out.append('Expected result fields:\n')
            out.append('```json\n' + json.dumps(case['expected'], indent=2, ensure_ascii=False) + '\n```\n')
    out.append(USAGE_FOOTER)
    return '\n'.join(out)


def write_outputs():
    for p, text in {root / 'fixtures_wbtest.mbt': render_tests() + '\n', root / 'docs/usage.md': render_usage()}.items():
        p.write_text(text, encoding='utf-8')
    # The formatter wraps the generated tests; keep its layout authoritative.
    subprocess.run(['moon', 'fmt'], cwd=root, capture_output=True)


def main():
    outputs = [root / 'fixtures_wbtest.mbt', root / 'docs/usage.md']
    saved = {p: p.read_text(encoding='utf-8') if p.exists() else None for p in outputs}
    write_outputs()
    if '--check' in sys.argv:
        stale = [str(p.relative_to(root)) for p in outputs if saved[p] != p.read_text(encoding='utf-8')]
        for p, text in saved.items():
            if text is not None:
                p.write_text(text, encoding='utf-8')
        if stale:
            print('Generated files are out of date:', ', '.join(stale), '- run python -B scripts/fixtures.py')
            return 1
        print('Fixture-derived files are up to date:', len(cases), 'cases')
        return 0
    print('Wrote', ', '.join(str(p.relative_to(root)) for p in outputs), 'from', len(cases), 'cases')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
